CREATE TABLE LOP(
	MALOP VARCHAR(20),
	TENLOP NVARCHAR(40) NOT NULL,
	SISO INT NOT NULL,
	CONSTRAINT PK_MALOP PRIMARY KEY(MALOP)
);
CREATE TABLE KHOA(
	MAKHOA VARCHAR(20),
	TENKHOA NVARCHAR(40) NOT NULL,
	CONSTRAINT PK_MAKHOA PRIMARY KEY(MAKHOA)
);
CREATE TABLE SINHVIEN(
	MASV VARCHAR(20),
	TENSV NVARCHAR(40) NOT NULL,
	NGAYSINH DATE NOT NULL,
	GIOITINH CHAR(10) NOT NULL,
	NIENKHOA VARCHAR(20) NOT NULL,
	MALOP VARCHAR(20) NOT NULL,
	MAKHOA VARCHAR(20) NOT NULL,
	CONSTRAINT PK_MASV PRIMARY KEY(MASV),
	CONSTRAINT FK_MALOP_SV FOREIGN KEY(MALOP) REFERENCES LOP(MALOP),
	CONSTRAINT FK_MAKHOA_SV FOREIGN KEY(MAKHOA) REFERENCES KHOA(MAKHOA)
);

CREATE TABLE THESV(
	MATHE VARCHAR(20),
	NGAYCAP DATE NOT NULL,
	NGAYHETHAN DATE NOT NULL,
	MASV VARCHAR(20),
	CONSTRAINT PK_MATHE PRIMARY KEY(MATHE),
	CONSTRAINT FK_THE_SV FOREIGN KEY(MASV) REFERENCES SINHVIEN(MASV)
);

CREATE TABLE GIANGVIEN(
	MAGV VARCHAR(20),
	TENGV NVARCHAR(50) NOT NULL,
	CHUYENMON NVARCHAR(30) NOT NULL,
	MAKHOA VARCHAR(20),
	CONSTRAINT PK_MAGV PRIMARY KEY(MAGV),
	CONSTRAINT FK_MAKHOA_GV FOREIGN KEY(MAKHOA) REFERENCES KHOA(MAKHOA) 
);

CREATE TABLE MONHOC(
	MAMH VARCHAR(20),
	TENMH NVARCHAR(40) NOT NULL,
	SOTC INT,
	CONSTRAINT PK_MAMH PRIMARY KEY(MAMH)
);

CREATE TABLE LOPHP(
	MAHP VARCHAR(20),
	TENHP NVARCHAR(40) NOT NULL,
	SLDANGKY INT NOT NULL,
	SLGIOIHAN INT NOT NULL,
	MAGV VARCHAR(20),
	MAMH VARCHAR(20),
	CONSTRAINT PK_MAHP PRIMARY KEY(MAHP),
	CONSTRAINT FK_MAGV_LOPHP FOREIGN KEY(MAGV) REFERENCES GIANGVIEN(MAGV),
	CONSTRAINT FK_MAMH_LOPHP FOREIGN KEY(MAMH) REFERENCES MONHOC(MAMH)
);

CREATE TABLE HOC(
	MASV VARCHAR(20),
	MAHP VARCHAR(20),
	DIEMTK DECIMAL(4,2) NOT NULL,
	DIEMGK DECIMAL(4,2) NOT NULL,
	DIEMCK DECIMAL(4,2) NOT NULL,
	CONSTRAINT PK_DIEM_SV PRIMARY KEY(MASV,MAHP),
	CONSTRAINT FK_MASV_DIEM FOREIGN KEY(MASV) REFERENCES SINHVIEN(MASV),
	CONSTRAINT FK_MAHP_DIEM FOREIGN KEY(MAHP) REFERENCES LOPHP(MAHP)
);
