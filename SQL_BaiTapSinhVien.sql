--1. Lấy danh sách sinh viên thuộc khoa "Khoa Công nghệ Thông tin"
SELECT S.MASV AS "Mã SSSV", 
		S.TENSV AS "Họ Tên Sinh Viên",
		S.NGAYSINH AS "Ngày Sinh",
		S.MALOP AS "Lớp"
FROM SINHVIEN S, KHOA K
WHERE S.MAKHOA = K.MAKHOA AND K.TENKHOA = N'Khoa Công Nghệ Thông Tin';

--2. Liệt kê thông tin sinh viên kèm thông tin thẻ sinh viên tương ứng
SELECT S.MASV, S.TENSV, T.MATHE
FROM SINHVIEN S, THESV T
WHERE S.MASV = T.MASV
--3. Đếm số lượng sinh viên trong từng lớp
SELECT S.MALOP, L.TENLOP, COUNT(*) AS 'SL'
FROM SINHVIEN S, LOP L
WHERE S.MALOP = L.MALOP
GROUP BY S.MALOP, L.TENLOP

--4. Danh sách các lớp học phần và giảng viên phụ trách
SELECT HP.MAHP, HP.TENHP, GV.TENGV, GV.CHUYENMON, MH.TENMH
FROM LOPHP HP, GIANGVIEN GV, MONHOC MH
WHERE HP.MAGV = GV.MAGV AND HP.MAMH = MH.MAMH

--5. Tìm các lớp học phần đã đủ hoặc vượt sĩ số giới hạn
SELECT *
FROM LOPHP HP, MONHOC MH
WHERE HP.MAMH = MH.MAMH AND HP.SLDANGKY >= HP.SLGIOIHAN

--6. Tính điểm tổng kết môn học của sinh viên theo công thức trọng số 
-- (Trọng số giả định: Điểm TK 10%, Điểm GK 30%, Điểm CK 60%)

SELECT S.MASV, S.TENSV, HP.TENHP
		,SUM(Đ.DIEMTK * 0.1 + Đ.DIEMGK * 0.3 + Đ.DIEMCK * 0.6) AS 'Tổng kết môn học'
FROM HOC Đ, SINHVIEN S, LOPHP HP
WHERE S.MASV = Đ.MASV AND HP.MAHP = Đ.MAHP 
GROUP BY S.MASV, S.TENSV, HP.TENHP, Đ.DIEMTK * 0.1 + Đ.DIEMGK * 0.3 + Đ.DIEMCK * 0.6

--7. Danh sách sinh viên đạt điểm cuối kỳ (DIEMCK) từ 8.0 trở lên
SELECT S.MASV, S.TENSV, HP.TENHP, Đ.DIEMCK
FROM SINHVIEN S, HOC Đ, LOPHP HP
WHERE S.MASV = Đ.MASV AND HP.MAHP = Đ.MAHP  AND Đ.DIEMCK >= 8

--8. Tính điểm cuối kỳ trung bình theo từng lớp học phần
SELECT HP.MAHP,HP.TENHP,CAST(AVG(Đ.DIEMCK) AS DECIMAL(4,2)) AS 'Điểm cuối kỳ trung bình'
FROM HOC Đ, LOPHP HP
WHERE Đ.MAHP = HP.MAHP
GROUP BY HP.MAHP,HP.TENHP

--9. Tìm giảng viên chưa được phân công dạy lớp học phần nào
SELECT GV.TENGV
FROM GIANGVIEN GV, LOPHP HP
WHERE GV.MAGV = HP.MAGV AND HP.MAHP = NULL
GROUP BY GV.TENGV

--10. Tìm sinh viên có điểm tổng kết môn cao nhất trong từng lớp học phần
SELECT TOP 1 S.MASV, S.TENSV, HP.TENHP
		,SUM(Đ.DIEMTK * 0.1 + Đ.DIEMGK * 0.3 + Đ.DIEMCK * 0.6) AS Tổng_kết_môn_học
FROM HOC Đ, SINHVIEN S, LOPHP HP
WHERE S.MASV = Đ.MASV AND HP.MAHP = Đ.MAHP 
GROUP BY S.MASV, S.TENSV, HP.TENHP, Đ.DIEMTK * 0.1 + Đ.DIEMGK * 0.3 + Đ.DIEMCK * 0.6
ORDER BY Tổng_kết_môn_học DESC