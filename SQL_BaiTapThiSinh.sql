DROP TABLE NGANH
DROP TABLE THI_SINH

CREATE TABLE PHONG_THI(
	MA_DD VARCHAR(50),
	SO_PHONG INT,
	CONSTRAINT PK_PHONG_THI PRIMARY KEY (MA_DD, SO_PHONG),
	CONSTRAINT FK_MA_DD_DIADIEMTHI FOREIGN KEY (MA_DD) REFERENCES DIADIEMTHI(MA_DD)
);

CREATE TABLE NGANH(
	MA_NGANH VARCHAR(50),
	TEN_NGANH VARCHAR(100),
	CONSTRAINT PK_MA_NGANH PRIMARY KEY (MA_NGANH)
);

CREATE TABLE THI_SINH(
	SOBD CHAR(10),
	HOTEN VARCHAR(20),
	NGAYSINH DATE,
	PHAI CHAR(5),
	MA_NGANH VARCHAR(50),
	MA_DD VARCHAR(50),
	SO_PHONG INT,
	CONSTRAINT PK_SOBD PRIMARY KEY(SOBD),
	CONSTRAINT FK_MA_NGANH_NGANH FOREIGN KEY (MA_NGANH) REFERENCES NGANH(MA_NGANH),
	CONSTRAINT FK_THI_SINH FOREIGN KEY (MA_DD,SO_PHONG) REFERENCES PHONG_THI(MA_DD,SO_PHONG)
);

