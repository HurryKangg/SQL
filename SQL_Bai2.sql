--TRUY VẤN
--1. In ra họ tên sinh viên và tên lớp của sinh viên đó
SELECT S.TENSV, L.TENLOP
FROM SINHVIEN S, LOP L
WHERE S.MALOP = L.MALOP

--2. Đếm số sinh viên của mỗi lớp, in ra tên lớp, mã lớp, số lượng sinh viên
SELECT S.MALOP,L.TENLOP, COUNT(*) AS SLSV
FROM SINHVIEN S, LOP L
WHERE S.MALOP = L.MALOP
GROUP BY S.MALOP, L.TENLOP

--3. Đếm số lượng sinh viên của mỗi lớp, chỉ hiện thị lớp có trên 4 SV. IN RA MALOP VA SLSV
SELECT S.MALOP, COUNT(*) AS SLSV
FROM SINHVIEN S
GROUP BY S.MALOP
HAVING COUNT(*) > 4

--4. Tính trung bình của từng môn học và sắp xếp giảm dần theo điểm trung bình
SELECT D.MAMH, AVG(D.DIEM) AS DIEMTB
FROM DIEM D
GROUP BY D.MAMH
ORDER BY DIEMTB DESC

--5. Tìm lớp có nhiều sinh viên
SELECT TOP 1 S.MALOP, COUNT(*) AS SLSV
FROM SINHVIEN S
GROUP BY S.MALOP
ORDER BY SLSV DESC
