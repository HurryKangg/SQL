CREATE DATABASE QuanLyPhong
USE QuanLyPhong

CREATE TABLE LOAIPHONG(
	MALOAI VARCHAR(20),
	TENLOAI NVARCHAR(100) NOT NULL,
	DONGIATHUE DECIMAL(18,2) NOT NULL,
	CONSTRAINT PK_MALOAI PRIMARY KEY(MALOAI)
);

CREATE TABLE PHONG(
	MAPHONG VARCHAR(20),
	TENPHONG NVARCHAR(100) NOT NULL,
	MALOAI VARCHAR(20),
	CONSTRAINT PK_MAPHONG PRIMARY KEY(MAPHONG),
	CONSTRAINT FK_MALOAI_PHONG FOREIGN KEY(MALOAI) REFERENCES LOAIPHONG(MALOAI)
);

CREATE TABLE KHACHTRO(
	MAKHACH VARCHAR(20),
	HOTEN NVARCHAR(100) NOT NULL,
	CCCD VARCHAR(20) NOT NULL,
	DIACHI NVARCHAR(100) NOT NULL,
	QUOCTICH NVARCHAR(50) NOT NULL,
	CONSTRAINT PK_MAKHACH PRIMARY KEY(MAKHACH)
);
CREATE TABLE PHIEUTHUE(
	MAPHIEU VARCHAR(20),
	NGAYBD DATE NOT NULL,
	NGAYKT DATE NOT NULL,
	MAKHACH VARCHAR(20),
	CONSTRAINT PK_MAPHIEU PRIMARY KEY(MAPHIEU),
	CONSTRAINT FK_MAKHACH_PHIEUTHUE FOREIGN KEY(MAKHACH) REFERENCES KHACHTRO(MAKHACH)
);
CREATE TABLE PHIEUSUDUNGDV(
	MAPHIEUDV VARCHAR(20),
	NGAYSD DATE NOT NULL,
	TONGTIEN DECIMAL(18,2) NOT NULL,
	MAPHIEU VARCHAR(20),
	CONSTRAINT PK_MAPHIEUDV PRIMARY KEY(MAPHIEUDV),
	CONSTRAINT FK_MAPHIEU_PHIEUSUDUNGDV FOREIGN KEY(MAPHIEU) REFERENCES PHIEUTHUE(MAPHIEU)
);
CREATE TABLE DANHMUCDV(
	MADV VARCHAR(20),
	TENDV NVARCHAR(100) NOT NULL,
	DONGIADV DECIMAL(18,2) NOT NULL,
	CONSTRAINT PK_MADV PRIMARY KEY(MADV)
);

CREATE TABLE CHITIETSDDV(
	MADV VARCHAR(20),
	MAPHIEUDV VARCHAR(20),
	SOLUONG INT NOT NULL,
	CONSTRAINT PK_CTSDDV PRIMARY KEY(MADV,MAPHIEUDV),
	CONSTRAINT FK_MADV_CTSDDV FOREIGN KEY(MADV) REFERENCES DANHMUCDV(MADV),
	CONSTRAINT FK_MAPHIEUDV_CTSDDV FOREIGN KEY(MAPHIEUDV) REFERENCES PHIEUSUDUNGDV(MAPHIEUDV)
);
CREATE TABLE HOADON(
	MAHD VARCHAR(20),
	NGAYLAP DATE NOT NULL,
	TONGTIENPHONG DECIMAL(18,2) DEFAULT 0,
	TONGTIENDV DECIMAL(18,2) DEFAULT 0,
	THANHTIEN DECIMAL(18,2) DEFAULT 0,
	MAPHIEU VARCHAR(20),
	CONSTRAINT PK_MAHD PRIMARY KEY(MAHD),
	CONSTRAINT FK_MAPHIEU_HOADON FOREIGN KEY(MAPHIEU) REFERENCES PHIEUTHUE(MAPHIEU)
);



CREATE TABLE CHITIETPHIEUTHUE(
	MAPHONG VARCHAR(20),
	MAPHIEU VARCHAR(20),
	CONSTRAINT PK_CTTHUEPHONG PRIMARY KEY(MAPHONG,MAPHIEU),
	CONSTRAINT FK_MAPHONG_CTTHUEPHONG FOREIGN KEY(MAPHONG) REFERENCES PHONG(MAPHONG),
	CONSTRAINT FK_MAPHIEU_CTTHUEPHONG FOREIGN KEY(MAPHIEU) REFERENCES PHIEUTHUE(MAPHIEU)
);
